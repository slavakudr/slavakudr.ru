-- Клиенты --------------------------------------------------

CREATE TABLE customers (
    customer_id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_first_name varchar(64) NOT NULL,
    customer_last_name varchar(64) NOT NULL,
    customer_middle_name varchar(64) NOT NULL
);

