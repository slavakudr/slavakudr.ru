-- Заказы --------------------------------------------------

CREATE TABLE orders (
    order_id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_id int REFERENCES customers(customer_id) NOT NULL,
    order_date date NOT NULL,
    order_time time NOT NULL
);

